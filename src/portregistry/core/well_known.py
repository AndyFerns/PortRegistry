def label_for(port: int, protocol: str | None = None) -> str | None:
    """Best label for a port, preferring a protocol-specific entry."""
    entry = _TABLE.get((port, protocol)) if protocol else None
    if entry is None:
        entry = _TABLE.get((port, None))
    if entry is None and protocol is None:
        entry = _TABLE.get((port, "tcp")) or _TABLE.get((port, "udp"))
    return entry[0] if entry else None


def category_for(port: int, protocol: str | None = None) -> str | None:
    entry = (_TABLE.get((port, protocol)) if protocol else None) or _TABLE.get((port, None))
    return entry[1] if entry else None


def table_size() -> int:
    return len(_TABLE)
